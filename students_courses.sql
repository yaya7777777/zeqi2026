-- ---------------------------------------------------------------------
-- DQL 9：查询没有选任何课程的学生姓名
-- ---------------------------------------------------------------------
-- 【解题思路】（经典"查 A 中在 B 里没有的"，3 种常见写法，推荐 NOT EXISTS 性能最好）
--
-- 核心：学生表有 10 人，选课表 sc 里出现过 sno 的只有 9 人。要找 sc 里**从没出现**过的 sno。
--
-- 写法 1（推荐）：NOT EXISTS 子查询
--   → 对每个学生 s，检查 sc 中有没有 sno=s.sno 的行，完全找不到 = 这个学生没选课
--   → 优点：即使 sc.sno 有 NULL 值也正确，性能好（可以利用 sc 上 sno 的索引）
--
-- 写法 2：NOT IN 子查询
--   → WHERE sno NOT IN (SELECT sno FROM sc WHERE sno IS NOT NULL)
--   → 缺点：如果子查询里 sno 有 NULL，结果会全空（坑！），不推荐
--
-- 写法 3：LEFT JOIN 找 NULL
--   → 学生表 LEFT JOIN sc，连接不上的那些行 sc.sno 列就是 NULL，说明没选课
--   → 写法简单直观
--
-- 【考察点】"反连接 / 差集"的三种写法

-- 写法 1（推荐，通用最佳实践，数据库优化器最喜欢）：
SELECT s.sname
  FROM student s
 WHERE NOT EXISTS (
           SELECT 1            -- SELECT 1/SELECT * 都可以，这里不关心选什么列，只关心"有没有行"
             FROM sc
            WHERE sc.sno = s.sno   -- 外层表的 sno 和子查询关联
       );

/*
-- 写法 3（LEFT JOIN 找空，简单直观，考试中写错风险最低）：
SELECT s.sname
  FROM student s
  LEFT JOIN sc ON s.sno = sc.sno   -- 左连接：student 保留全部行，sc 匹配不到的列全部变 NULL
 WHERE sc.sno IS NULL;             -- 筛选 sc.sno 为 NULL 的行 = 没匹配到选课记录的 = 没选课
