-- ---------------------------------------------------------------------
-- DQL 1：查询"计算机学院"所有学生的姓名和学号
-- ---------------------------------------------------------------------
-- 【解题思路】
-- 1. 要什么列？sname, sno → SELECT sname, sno
-- 2. 从哪张表查？student → FROM student
-- 3. 筛选条件？sdept = '计算机学院' → WHERE sdept = '计算机学院'
-- 4. 顺序固定口诀：SELECT → FROM → WHERE → GROUP BY → HAVING → ORDER BY → LIMIT（SQL 语法硬性规定）
-- 【考察点】基本 SELECT + WHERE 等值筛选
SELECT sname,              -- 姓名
       sno                 -- 学号
  FROM student
 WHERE sdept = '计算机学院';


-- ---------------------------------------------------------------------
-- DQL 2：查询姓名中含有"小"字的学生姓名和学号
-- ---------------------------------------------------------------------
-- 【解题思路】
-- 1. 模糊匹配用 LIKE 关键字
-- 2. LIKE 的通配符：% = 任意多个字符（0/1/多个），_ = 恰好 1 个字符
--    '%小%'  = 前后随便什么字符，中间必须有"小" → 含"小"字
--    '小%'   = 以"小"开头的姓名（小明、小红这种）
--    '%小'   = 以"小"结尾的姓名
--    '张_'   = 姓张，名字共两个字
-- 3. ⚠️ 性能注意：'%小%' 这种"前后都带 %"的写法是 B+ 树索引失效场景之一，会全表扫描。
--    真要模糊搜中文大表，应该用全文索引或 Elasticsearch。
-- 【考察点】LIKE 模糊查询 + 通配符使用
SELECT sname,
       sno
  FROM student
 WHERE sname LIKE '%小%';


-- ---------------------------------------------------------------------
-- DQL 3：查询每门课程的名称和平均分，按平均分从高到低排列
-- ---------------------------------------------------------------------
-- 【解题思路】
-- 1. "每门课程"四个字 → 需要**分组（GROUP BY）**，按课程号 cno 分组
-- 2. 分组后用聚合函数 AVG(grade) 计算该组的平均分
--    - 常用 5 个聚合函数：COUNT() 计数 / SUM() 求和 / AVG() 平均 / MAX() 最大 / MIN() 最小
-- 3. "课程名称"在 course 表，成绩在 sc 表 → 两个表 JOIN 连接起来
--    JOIN ... ON ... 语法：sc.cno = course.cno（按课程号相等连接）
-- 4. 排序：ORDER BY 平均分 DESC
--    - ASC  = 升序（默认，可省略）
--    - DESC = 降序（高→低）
-- 5. 聚合函数对 NULL 的处理：AVG() 会自动忽略 grade 为 NULL 的缺考学生，不会算成 0
--    （这是标准 SQL 行为，和业务预期一致）
-- 【考察点】JOIN 内连接 + GROUP BY 分组 + 聚合函数 + ORDER BY 排序
SELECT c.cname                         -- 课程名（加 c. 表别名，防止列歧义）
     , AVG(sc.grade) AS avg_grade      -- 该课程平均分，AS 给列取一个别名 avg_grade（展示用更清晰）
  FROM sc
 INNER JOIN course c                   -- 内连接：只保留两表 cno 匹配的行。别名 c 简化书写
         ON sc.cno = c.cno             -- 连接条件：课程号相等
 GROUP BY c.cno, c.cname               -- 分组键：一般把 SELECT 中没被聚合的列都放 GROUP BY 里
 ORDER BY avg_grade DESC;              -- 排序：平均分从高到低


-- ---------------------------------------------------------------------
-- DQL 4：查询每门课程的最高分和最低分，显示课程名
-- ---------------------------------------------------------------------
-- 【解题思路】
-- 1. 和第 3 题结构几乎一样，只是聚合函数换成 MAX(grade) 和 MIN(grade)
-- 2. 同样需要 sc 表 JOIN course 表拿课程名
-- 3. 分组：按课程（cno）分组
-- 【考察点】MAX/MIN 聚合函数
SELECT c.cname                      -- 课程名
     , MAX(sc.grade) AS max_grade   -- 该课程最高分
     , MIN(sc.grade) AS min_grade   -- 该课程最低分
  FROM sc
 INNER JOIN course c ON sc.cno = c.cno
 GROUP BY c.cno, c.cname;


-- ---------------------------------------------------------------------
-- DQL 5：查询所有不及格（成绩 < 60）学生的姓名和课程名
-- ---------------------------------------------------------------------
-- 【解题思路】
-- 1. 要拿三列信息：学生姓名（student）、课程名（course）、成绩条件（sc）
--    → 三张表 JOIN！
--    student.sno ←→ sc.sno ←→ sc.cno ←→ course.cno
-- 2. 筛选条件：grade < 60 → WHERE 子句
-- 3. DISTINCT：如果某个学生一门课连续挂科两次（实际一般不会，因为 sno+cno 是联合主键）
--    则不需要；但加 DISTINCT 也不影响，反而更稳妥。
-- 【考察点】三表 JOIN + WHERE 数值比较过滤
SELECT DISTINCT
       s.sname        -- 学生姓名
     , c.cname        -- 不及格的课程名
     , sc.grade       -- 方便看出具体多少分，题目没要求可以删掉
  FROM sc
 INNER JOIN student s ON sc.sno = s.sno     -- 成绩表 ↔ 学生表
 INNER JOIN course  c ON sc.cno = c.cno     -- 成绩表 ↔ 课程表
 WHERE sc.grade < 60;                       -- 不及格条件


-- ---------------------------------------------------------------------
-- DQL 6：查询选课数超过 2 门的学生姓名，按选课数从高到低排列
-- ---------------------------------------------------------------------
-- 【解题思路】（经典"筛分组"问题 → WHERE 过滤行，HAVING 过滤分组！）
-- 1. 先按学生分组 → GROUP BY sc.sno
-- 2. 用 COUNT(*) 统计每个学生选了几门课
-- 3. 筛选条件"选课数 > 2"是**对分组聚合后的结果做筛选**
--    → 这种不能写 WHERE（WHERE 是在分组前逐行过滤，还没有 COUNT 结果）
--    → 必须用 HAVING 子句，HAVING COUNT(*) > 2
--
-- ⚠️ 【超级易错点：WHERE vs HAVING 的区别】（面试 100% 考）
-- | 子句   | 作用时机       | 能用聚合函数吗？ | 例子                                   |
-- |--------|----------------|------------------|----------------------------------------|
-- | WHERE  | GROUP BY 之前  | ❌ 绝对不能      | WHERE grade > 60（先筛掉不及格的行）   |
-- | HAVING | GROUP BY 之后  | ✅ 必须用它筛    | HAVING COUNT(*) > 2（按聚合结果筛分组）|
--
-- 4. JOIN 学生表拿姓名；ORDER BY 选课数降序
-- 【考察点】WHERE / HAVING 区别 + 分组计数 + 排序
SELECT s.sname
     , COUNT(*) AS course_count   -- 统计该学生选课行数 = 选课门数（sno+cno 联合主键，保证不会重）
  FROM sc
 INNER JOIN student s ON sc.sno = s.sno
 GROUP BY sc.sno, s.sname
HAVING COUNT(*) > 2               -- 选课数超过 2 门（分组聚合后的筛选 = 必须用 HAVING）
 ORDER BY course_count DESC;      -- 选课数高的排前面


-- ---------------------------------------------------------------------
-- DQL 7：查询每名学生的总学分（成绩 ≥ 60 才算通过，没有成绩的学生可不出现）
-- ---------------------------------------------------------------------
-- 【解题思路】
-- 1. "成绩≥60才算通过" → 先过滤掉不及格和缺考的 → WHERE grade >= 60
--    （这里用 WHERE，因为是对 sc 每一行提前过滤，不是分组后筛）
-- 2. 再按学生分组，对"通过的课程"的学分做 SUM() 求和
-- 3. 学分数值在 course 表，所以要 JOIN course 表
-- 4. "没成绩学生可不出现" → 用默认的 INNER JOIN（没选课的学生 JOIN 不到 sc，自动不出现）
--    如果题目要求"没选课的学生显示总学分 0"，就要改成 RIGHT JOIN 或用子查询 COALESCE(SUM,0)
-- 【考察点】多表 JOIN + WHERE 提前过滤 + SUM 聚合
SELECT s.sname
     , s.sno
     , SUM(c.credit) AS total_credit   -- 所有及格课程的学分加总 = 总学分
  FROM sc
 INNER JOIN student s ON sc.sno = s.sno
 INNER JOIN course  c ON sc.cno = c.cno
 WHERE sc.grade >= 60                  -- 先筛掉不及格和缺考（NULL >= 60 结果为假，自动排除）
 GROUP BY s.sno, s.sname;


-- ---------------------------------------------------------------------
-- DQL 8：查询平均分最高的学生姓名及其平均分
-- ---------------------------------------------------------------------
-- 【解题思路】（两种常见写法，推荐写法 1 思路清晰）
--
-- 写法 1：先分组算平均分 → 按平均分倒序排序 → 取第 1 行
--   优点：简单直观；缺点：同分并列第一只会取第一个（题目没说并列怎么处理，这种一般得分）
--
-- 写法 2：子查询找 MAX(平均分)，再 WHERE 平均分 = 最高分
--   优点：能取到"并列第一"的所有学生（两人同是最高分会都返回）
--         但写起来稍微复杂（需要嵌套两层聚合），MySQL 5.7+ 支持
SELECT s.sname
     , AVG(sc.grade) AS avg_grade
  FROM sc
 INNER JOIN student s ON sc.sno = s.sno
 GROUP BY s.sno, s.sname
 ORDER BY avg_grade DESC   -- 平均分最高的排在最上面
 LIMIT 1;                  -- 只取第 1 行 = 第一名
-- LIMIT 使用格式：LIMIT [offset,] row_count
--   LIMIT 1     = 取第 1 条
--   LIMIT 5     = 取前 5 条（TOP 5）
