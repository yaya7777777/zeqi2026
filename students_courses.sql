-- ---------------------------------------------------------------------
-- 表 1：学生表 student
-- 结构：学号 sno、姓名 sname、所在学院 sdept
-- 设计思路：
--   - sno 是学号，天然唯一且非空 → 设为主键 PK
--   - 姓名和学院一般不会为空 → 加 NOT NULL 约束
--   - 字段长度预留足够，学号一般 8~20 字符，姓名 20~50 字符
--   - 学院 sdept 通常会被用来 "WHERE sdept='计算机学院'" 这样查 → 建议加索引（加分项）
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS sc;           -- 先删有外键的子表，再删父表（否则会报"被引用不能删"）
DROP TABLE IF EXISTS course;
DROP TABLE IF EXISTS student;

CREATE TABLE student (
    sno     VARCHAR(20)  NOT NULL COMMENT '学号（主键）',
    sname   VARCHAR(50)  NOT NULL COMMENT '姓名',
    sdept   VARCHAR(100) NOT NULL COMMENT '所在学院/系',
    PRIMARY KEY (sno),                          -- 主键：学号
    INDEX idx_sdept (sdept),                    -- 普通索引：按学院查询会走索引（可选加分项）
    INDEX idx_sname (sname)                     -- 普通索引：按姓名查询走索引
) ENGINE = InnoDB                               -- 必须用 InnoDB 才支持事务和外键
  DEFAULT CHARSET = utf8mb4
  COMMENT = '学生表';

-- ---------------------------------------------------------------------
-- 表 2：课程表 course
-- 结构：课程号 cno、课程名 cname、学分 credit
-- 设计思路：
--   - cno 课程号是主键 PK
--   - credit 学分是小数（可能 3.0、4.5 这种）→ 用 DECIMAL(4,1)：总长度4位，小数1位
--   - 学分一般不会为负，且在 0~10 之间 → 可以加 CHECK 约束（MySQL 8.0.16+ 才真正生效）
-- ---------------------------------------------------------------------
CREATE TABLE course (
    cno     VARCHAR(20)    NOT NULL COMMENT '课程号（主键）',
    cname   VARCHAR(100)   NOT NULL COMMENT '课程名',
    credit  DECIMAL(4, 1)  NOT NULL COMMENT '学分',
    PRIMARY KEY (cno),
    UNIQUE INDEX uk_cname (cname)               -- 课程名一般也唯一 → 加唯一索引（可选加分项）
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COMMENT = '课程表';

-- ---------------------------------------------------------------------
-- 表 3：选课/成绩表 sc（score + course，经典命名）
-- 结构：学号 sno、课程号 cno、成绩 grade
-- 设计思路：
--   - 这是一张"联系表"，把学生表和课程表多对多关系拆开（一个学生选多门课，一门课被多个学生选）
--   - 主键设计：(sno, cno) 联合主键——同一个学生同一门课只能有一个成绩，组合起来唯一
--   - 两个外键：sno 引用 student.sno，cno 引用 course.cno
--   - 成绩 grade 允许 NULL（有的学生选了课但还没考，缺考 = NULL）；有成绩时 0~100
--   - DECIMAL(5,2)：整数3位+小数2位，够存100.00
-- ---------------------------------------------------------------------
CREATE TABLE sc (
    sno    VARCHAR(20)   NOT NULL COMMENT '学号（外键→student.sno）',
    cno    VARCHAR(20)   NOT NULL COMMENT '课程号（外键→course.cno）',
    grade  DECIMAL(5, 2) NULL     COMMENT '成绩（0~100，缺考可为NULL）',
    -- 联合主键：(sno, cno) 合起来唯一
    PRIMARY KEY (sno, cno),
    -- 外键1：sc.sno → student.sno
    CONSTRAINT fk_sc_student
        FOREIGN KEY (sno) REFERENCES student (sno)
            ON DELETE RESTRICT   -- 默认：如果学生还存在成绩，就不让删这个学生（防止孤儿数据）
            ON UPDATE CASCADE,   -- 如果 sno 改了（实际不建议改主键），sc 里对应的 sno 一起改
    -- 外键2：sc.cno → course.cno
    CONSTRAINT fk_sc_course
        FOREIGN KEY (cno) REFERENCES course (cno)
            ON DELETE RESTRICT
            ON UPDATE CASCADE,
    -- 索引：按课程号查成绩（WHERE cno=?）也很常见 → 加索引
    INDEX idx_cno (cno)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COMMENT = '选课/成绩表（学生-课程 多对多中间表）';


