-- -----------------------------------------------------------------------------
-- 表：users （用户主表）
-- -----------------------------------------------------------------------------
-- 【设计思路·面试考点】
--   1. 主键 id：自增 INTEGER（SQLite 中 INTEGER PRIMARY KEY = 自增 alias for ROWID）
--   2. username：用户名，加 UNIQUE 约束防重名 → 违反返回 409 Conflict（招新题第 6 步要求）
--   3. password：题目允许明文存储（生产环境必须 bcrypt/Argon2 哈希！）
--   4. created_at / updated_at：时间戳，DEFAULT CURRENT_TIMESTAMP 自动填值
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,    -- 主键：自增用户 ID
    username    VARCHAR(50)  NOT NULL UNIQUE,         -- 用户名（唯一，不可重复）
    password    VARCHAR(255) NOT NULL,                -- 密码（题目允许明文，生产必须 bcrypt）
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,   -- 创建时间
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP    -- 最后更新时间
);

-- -----------------------------------------------------------------------------
-- 可选：初始化一条测试管理员账号（方便你直接登录，id=1）
--   用户名：admin   密码：admin123
-- -----------------------------------------------------------------------------
INSERT OR IGNORE INTO users (id, username, password)
VALUES (1, 'admin', 'admin123');
